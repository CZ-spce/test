% (3)压控电压源二阶 HPF 完整代码：含传递函数+截止频率求解+相位平移计算+波特图+标注
C1=2.2e-6;
C2=2.2e-6;
R1=22000;
R2=22000;
R3=2000;
R4=2000;
A=(R3+R4)/R3;  % 同相放大倍数
f=1/sqrt(C1*C2*R1*R2)/6.28 % 你原有的近似截止频率
Q=sqrt(C1*C2*R1*R2)/((C1+C2)*R1+(1-A)*C2*R2) ; % 品质因数
s=tf('s');
% 二阶高通滤波器传递函数（你的原式，完全保留）
T=A*C1*C2*R1*R2*s^2/(1+((C1+C2)*R1+(1-A)*C2*R2)*s+C1*C2*R1*R2*s^2);

figure;
bode(T)

%% ========== 新增1：从传递函数精准求解【-3dB截止频率】(二阶滤波器标准截止频率) ==========
[mag,phase,w] = bode(T);        % 提取传递函数的幅值mag、相位phase(相位平移)、角频率w
mag_dB = 20*log10(squeeze(mag));% 幅值转分贝(dB)，squeeze消除多余维度
freq = w/(2*pi);               % 角频率转实际频率 Hz
A_dB = 20*log10(A);            % 二阶高通的通带增益(最大值)
cutoff_dB = A_dB - 3;          % 截止频率的判定标准：通带增益衰减3dB
% 插值计算精准的截止频率(核心)，解决离散点无刚好-3dB的问题
fc_precise = interp1(mag_dB, freq, cutoff_dB, 'linear', 'extrap')

